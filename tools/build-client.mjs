// Reproducible client artifact. React is supplied by DSH, not bundled twice.
import {build} from 'esbuild'
import {readFile, writeFile, mkdir} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const target = path.join(root, 'lib/client.js')
const result = await build({
  absWorkingDir:root, entryPoints:[path.join(root, 'web/index.jsx')], bundle:true, write:false,
  format:'cjs', platform:'browser', target:['chrome110'], external:['react'],
  loader:{'.css':'text'}, charset:'utf8', legalComments:'none', minify:false,
  logLevel:'silent',
  banner:{js:'// Generated by npm run build:client. Edit web/, not this artifact.\nwindow.__ModuleLoader__.load({ id: "dsh-dafeiyu-growth", factory: (require) => {\nconst module = { exports: {} }; const exports = module.exports;'},
  footer:{js:'return module.exports;\n} });'},
})
const source = result.outputFiles[0].text
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) {
    console.error('Client artifact is stale; run npm run build:client and commit lib/client.js.')
    process.exitCode = 1
  } else console.log('Client artifact matches web/ sources.')
} else {
  await mkdir(path.dirname(target), {recursive:true})
  await writeFile(target, source, 'utf8')
  console.log(`Built lib/client.js (${Buffer.byteLength(source)} bytes); React remains external.`)
}
